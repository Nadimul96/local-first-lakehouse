def _asset(name: str) -> str:
    return (files(__package__) / "assets" / name).read_text(encoding="utf-8")


def render_report(snapshot: dict[str, Any]) -> str:
    settings = snapshot["settings"]
    subtitle = f"run report · {settings['store']} store · {settings['key_provider']} keys"
    stamp = snapshot["generated_at"][:19].replace("T", " ")
    body = "".join(
        [
            verdict(snapshot),
            pipeline(snapshot),
            timeline(snapshot),
            queue(snapshot),
            verification(snapshot),
            '<div class="grid-2">',
            ingest(snapshot),
            tiering(snapshot),
            "</div>",
            gold(snapshot),
        ]
    )
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>Lakehouse run report</title>
<style>{_asset("report.css")}</style>
</head>
<body>
<div class="wrap">
<header class="topbar">
  <div class="brand">{_LOGO}<strong>local-first-lakehouse</strong><span>{esc(subtitle)}</span></div>
  <div class="meta"><span class="stamp">{esc(stamp)} UTC</span>
    <button class="theme-toggle" type="button" aria-label="Toggle dark mode">
      {_THEME_ICONS}</button></div>
</header>
<main>{body}</main>
<footer class="foot">
  <span>Generated by <code>lakehouse report</code> on {esc(snapshot["machine"])}.
    Synthetic data.</span>
  <span>Reproduce: <code>uv run lakehouse demo</code></span>
</footer>
</div>
<script>{_asset("report.js")}</script>
</body>
</html>
"""
